export const getItem = id => ITEMS.find(item => item.id === id);

export function filterItems({ kind = '전체', query = '' } = {}) {
  const needle = query.trim().toLocaleLowerCase('ko');
  return ITEMS.filter(item =>
    (kind === '전체' || item.kind === kind) &&
    (!needle || `${item.id} ${item.affixId} ${item.name} ${item.slot} ${item.effect} ${item.motif}`.toLocaleLowerCase('ko').includes(needle))
  );
}
