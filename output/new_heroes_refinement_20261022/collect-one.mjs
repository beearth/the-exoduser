import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const [candidate,url,destination]=process.argv.slice(2);
if(!candidate||!url||!destination)throw new Error('candidate url relativeDestination required');
const root='G:/exoduser',out=path.join(root,'output/new_heroes_refinement_20261022');
const file=path.resolve(root,destination);
if(!file.startsWith(path.resolve(root)+path.sep))throw new Error('Destination outside workspace');
const receipt=JSON.parse(fs.readFileSync(path.join(out,'submission-receipt.json')));
const job=receipt.jobs.find(j=>j.candidate===candidate);
const sourceUrl=new URL(url);
if(!job||sourceUrl.hostname!=='skillsrc.octask.ai'||!(sourceUrl.pathname.includes('/'+job.task+'/')||sourceUrl.pathname.startsWith('/seedream/'+job.task+'_')))throw new Error('Task/source mismatch');
const response=await fetch(url);
if(!response.ok)throw new Error(`Download HTTP ${response.status}`);
const data=Buffer.from(await response.arrayBuffer());
if(data.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw new Error('Not PNG');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
fs.mkdirSync(path.dirname(file),{recursive:true});
if(!fs.existsSync(file))fs.writeFileSync(file,data,{flag:'wx'});
if(sha(fs.readFileSync(file))!==sha(data))throw new Error('Existing destination differs');
const desktop=path.join('C:/Users/심도진/Desktop/엑소듀서_검토/신규캐릭터_지속개선_20261022',path.basename(file));
fs.mkdirSync(path.dirname(desktop),{recursive:true});
if(!fs.existsSync(desktop))fs.copyFileSync(file,desktop,fs.constants.COPYFILE_EXCL);
if(sha(fs.readFileSync(desktop))!==sha(data))throw new Error('Desktop copy differs');
const row={candidate,url,destination,width:data.readUInt32BE(16),height:data.readUInt32BE(20),bytes:data.length,sha256:sha(data),desktopCopy:desktop,status:'completed-downloaded',recordedAt:new Date().toISOString()};
const downloadFile=path.join(out,'download-receipt.json'),downloads=JSON.parse(fs.readFileSync(downloadFile));
if(!downloads.rows.some(r=>r.candidate===candidate))downloads.rows.push(row);
fs.writeFileSync(downloadFile,JSON.stringify(downloads,null,2)+'\n');
Object.assign(job,{status:row.status,savedPath:destination,sha256:row.sha256});
fs.writeFileSync(path.join(out,'submission-receipt.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(row,null,2));
