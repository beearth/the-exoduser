  function sway(it,now,s){
    if(s<=0)return 0;
    const g=gust(now,it.x),A=amp(it)*g;
    const main=Math.sin(now*.00105+it.phase+it.x*.0006);
    const flutter=.32*Math.sin(now*.0029+it.phase2)*Math.pow(s,2.4);
    return A*(Math.pow(s,1.7)*main+flutter);
  }
  // shear k about the current origin: M=[[1,k],[0,1]] = R(phi)·diag(sx,sy)·R(theta)
  function shear(ctx,k){
    if(Math.abs(k)<1e-5)return;
    const E=1,F=0,G=k/2,H=-k/2;
    const Q=Math.sqrt(E*E+H*H),R=Math.sqrt(F*F+G*G),sx=Q+R,sy=Q-R;
    const a1=Math.atan2(G,F),a2=Math.atan2(H,E),theta=(a2-a1)/2,phi=(a2+a1)/2;
    ctx.rotate(phi);ctx.scale(sx,sy);ctx.rotate(theta);
  }
  function hOf(it){return it.anchorY-it.y;} // world height from canopy top to anchor
  function sOf(it,wy){return Math.max(0,Math.min(1,(it.anchorY-wy)/hOf(it)));}
  // Draw the tree body (rows srcY0..srcY1 of the atlas) in 5 sheared slices + root rows unswayed.
  function blitSwayed(ctx,tex,it,now){
    const S=it.side,k=it.k,anchorPx=Math.max(0,Math.min(S,(it.anchorY-it.y)/k));
    let draws=0;
    if(anchorPx<S){ctx.drawImage(tex,0,anchorPx,S,S-anchorPx,it.x,it.y+anchorPx*k,it.w,(S-anchorPx)*k);draws++;}
    for(let j=0;j<SLICES.length-1;j++){
      const sLo=SLICES[j],sHi=SLICES[j+1];
      const yBotW=it.anchorY-sLo*hOf(it),yTopW=it.anchorY-sHi*hOf(it);
      const srcBot=(yBotW-it.y)/k,srcTop=Math.max(0,(yTopW-it.y)/k);
      if(srcBot-srcTop<1)continue;
      const dBot=sway(it,now,sLo),dTop=sway(it,now,sHi);
      const kk=-(dTop-dBot)/Math.max(1,yBotW-yTopW);
      ctx.save();ctx.translate(it.x+dBot,yBotW);shear(ctx,kk);
      // 0.6px overlap hides hairline seams between slices
      const ov=j<SLICES.length-2?.6:0;
      ctx.drawImage(tex,0,srcTop-ov,S,srcBot-srcTop+ov,0,(srcTop-ov)*k-(yBotW-it.y),it.w,(srcBot-srcTop+ov)*k);
      ctx.restore();draws++;
    }
    return draws;
  }
  // weights: optional per-feature alpha multipliers (border band strength); 0 skips the feature.
  function drawFeatures(ctx,tex,it,now,baseAlpha,weights){
    let draws=0;
    for(let fi=0;fi<it.feats.length;fi++){
      const f=it.feats[fi];
      if(!f.pw)continue;
      const alpha=baseAlpha*(weights?weights[fi]:1);
      if(alpha<.04)continue;
      ctx.globalAlpha=alpha;
      const wy=it.y+f.cy*it.k,dx=sway(it,now,sOf(it,wy));
      const ox=it.x+f.px*it.k+dx,oy=it.y+f.py*it.k,dw=f.pw*it.k,dh=f.ph*it.k;
      if(f.k==='e'){
        if(!f.nextBlink)f.nextBlink=now+600+f.seed()*5200;
        if(now>=f.nextBlink&&f.blinkStart<0){f.blinkStart=now;f.nextBlink=now+(f.seed()<.16?380:1900+f.seed()*5200);}
        if(f.blinkStart>=0){
          const hold=f.dbgHold||70,t=now-f.blinkStart;let a=0;
          if(t<100)a=t/100;else if(t<100+hold)a=1;else if(t<220+hold)a=1-(t-100-hold)/120;else{f.blinkStart=-1;f.dbgHold=0;}
          if(f.blinkStart>=0&&a>0){ctx.globalAlpha=a*alpha;ctx.drawImage(tex,f.lx,f.ly,f.pw,f.ph,ox,oy,dw,dh);ctx.globalAlpha=alpha;draws++;activeBlinks++;}
        }
      }else if(f.k==='m'){
        const p=.5+.5*Math.sin(now*f.speed+f.phase),s=1-.07*p*p;
        ctx.drawImage(tex,f.lx,f.ly,f.pw,f.ph,ox,oy,dw,dh*s);draws++;
      }else{
        const p=.5+.5*Math.sin(now*f.speed+f.phase),s=1+.06*p*p;
        ctx.drawImage(tex,f.lx,f.ly,f.pw,f.ph,ox-(dw*s-dw)/2,oy-(dh*s-dh)/2,dw*s,dh*s);draws++;
      }
    }
    return draws;
  }
  function canDraw(g,source){return g&&g.stage===0&&!g._bossArena&&!g._fieldRebuildQA&&source==='assets/map/ch1/production_finish';}
  // ── border-foreground band copy: atlas × bandAlpha (8px grid), same sway as the ground pass ──
  let bandFn=null;
  function setBandFn(fn){bandFn=typeof fn==='function'?fn:null;}
  function*bandJob(it,tex){
    const S=it.side,MS=8,mw=Math.ceil(S/MS)+1,mh=Math.ceil(S/MS)+1,bm=new Float32Array(mw*mh);
    for(let my=0;my<mh;my++){
      const wy=it.y+my*MS*it.k;
      for(let mx=0;mx<mw;mx++)bm[my*mw+mx]=bandFn(it.x+mx*MS*it.k,wy);
      if((my&15)===15)yield;
    }
    const c=cv(tex.width,tex.height),cc=c.getContext('2d',{willReadFrequently:true});
    cc.drawImage(tex,0,0);yield;
    for(let by=0;by<S;by+=64){
      const bh=Math.min(64,S-by),image=cc.getImageData(0,by,S,bh),d=image.data;
      for(let r=0;r<bh;r++){
        const y=by+r,fy=y/MS,y0=Math.min(mh-1,~~fy),y1=Math.min(mh-1,y0+1),ty=fy-y0;
        for(let x=0;x<S;x++){
          const k=(r*S+x)*4;if(!d[k+3])continue;
          const fx=x/MS,x0=Math.min(mw-1,~~fx),x1=Math.min(mw-1,x0+1),tx=fx-x0;
          const m=(bm[y0*mw+x0]*(1-tx)+bm[y0*mw+x1]*tx)*(1-ty)+(bm[y1*mw+x0]*(1-tx)+bm[y1*mw+x1]*tx)*ty;
          const al=d[k+3]*m;d[k+3]=al<6?0:al;
        }
      }
      cc.putImageData(image,0,by);
      yield;
    }
    c._glVer=1;
    it.band=c;it.bandJob=null;it.featBand=it.feats.map(function(f){return bandFn(it.x+f.cx*it.k,it.y+f.cy*it.k)});
  }
  function bandFor(it,now){
    const tex=texFor(it,now);if(!tex||!bandFn)return null;
    if(it.band)return it.band;
    if(!it.bandJob){it.bandJob=bandJob(it,tex);queue.push({job:it.bandJob,idx:it.idx,band:true});schedule();}
    return null;
  }
  // Ground pass: every tree (the border foreground lays a banded copy on top for the fg trees).
  function draw(ctx,g,now,source,width,height){
    lastDraws=0;activeBlinks=0;lastVisible=0;
    if(!canDraw(g,source))return 0;
    const started=root.performance.now();
    const zoom=Math.max(.3,g._edZoom||g._camZoom||1);
    const left=g.cam.x-width/(2*zoom)-24,right=g.cam.x+width/(2*zoom)+24,top=g.cam.y-height/(2*zoom)-24,bottom=g.cam.y+height/(2*zoom)+24;
    const prev=ctx.globalAlpha;
    for(let i=0;i<INSTANCES.length;i++){
      const it=INSTANCES[i];
      if(!it.baked)continue; // map-object trees are drawn by the y-sorted object loop (drawObj)
      if(it.x-16>right||it.x+it.w+16<left||it.y>bottom||it.y+it.h<top)continue;
      lastVisible++;
      const tex=texFor(it,now);if(!tex)continue;
      ctx.globalAlpha=1;
      lastDraws+=blitSwayed(ctx,tex,it,now);
      lastDraws+=drawFeatures(ctx,tex,it,now,1);
    }
    ctx.globalAlpha=prev;
    evict(now);
    const ms=root.performance.now()-started;drawSamples++;totalDrawMs+=ms;if(ms>maxDrawMs)maxDrawMs=ms;
    return lastDraws;
  }
  // Border foreground hook: the banded copy of one tree with the same sway, then the
  // animated overlays scaled by the band strength at each feature (so blinks stay visible).
  function drawTreeBand(ctx,idx,now,alpha){
    const it=byIdx.get(idx);if(!it)return 0;
    const band=bandFor(it,now);if(!band)return 0;
    const prev=ctx.globalAlpha;ctx.globalAlpha=alpha;
    const n=blitSwayed(ctx,band,it,now)+drawFeatures(ctx,band,it,now,alpha,it.featBand);
    ctx.globalAlpha=prev;return n;
  }
  // Hand-placed map-object trees (m_ctree13..20): the map object loop keeps y-sorting,
  // occlusion fade and collision; this only replaces its plain drawImage. Unprocessed art
  // (no brightness/rim/fade) to keep the previous look; foot pivot = depth-slice footYF .45.
  const objInst=new Map();
  function drawObj(ctx,mo,rt,sz,now){
    const key=mo.x+','+mo.y+','+sz;
    let it=objInst.get(key);
    if(!it){
      it=makeInstance({idx:1000+objInst.size,variant:rt[0],flip:rt[1],side:Math.max(64,Math.round(sz)),k:sz/Math.max(64,Math.round(sz)),
        bright:1,baked:false,x:mo.x-sz/2,y:mo.y-sz/2,anchorY:mo.y+sz*.45});
      objInst.set(key,it);INSTANCES.push(it);
    }
    const tex=texFor(it,now);if(!tex)return false;
    const base=ctx.globalAlpha;
    blitSwayed(ctx,tex,it,now);drawFeatures(ctx,tex,it,now,base);
    ctx.globalAlpha=base;return true;
  }
  function ready(idx){const it=byIdx.get(idx);return !!(it&&it.tex);}
  function qa(){
    let ready=0,pending=queue.length,erased=0;
    for(const it of INSTANCES){if(it.tex)ready++;else if(it.tex===false)erased++;}
    return{instances:INSTANCES.length,visible:lastVisible,ready:ready,erased:erased,pending:pending,builds:builds,
      cachedPx:cachedPx,lastDraws:lastDraws,activeBlinks:activeBlinks,sliceMsMax:Math.round(sliceMsMax*10)/10,
      drawSamples:drawSamples,meanDrawMs:drawSamples?totalDrawMs/drawSamples:0,maxDrawMs:maxDrawMs,version:'20261008-rotforest-98'};
  }
  function debugBlink(idx,fi,hold){const it=byIdx.get(idx);const f=it&&it.feats[fi];if(!f||f.k!=='e')return false;f.nextBlink=1;f.blinkStart=-1;f.dbgHold=hold||0;return true;}
  root.Ch1RotTrees=Object.freeze({draw:draw,drawObj:drawObj,drawTreeBand:drawTreeBand,setBandFn:setBandFn,ready:ready,qa:qa,
    debugBlink:debugBlink,_instances:function(){return INSTANCES},_trees:TREES,_feats:FEATS,_sway:sway,_shear:shear,_treeFade:treeFade});
