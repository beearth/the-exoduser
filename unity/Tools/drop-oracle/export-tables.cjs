// D01: generates unity/Assets/Exoduser/Runtime/Core/DropTablesData.cs from the ORIGINAL game.html tables (evaluated, not retyped).
//   node export-tables.cjs <game.html> <out.cs> <web-commit>
// Tables: AFFIX_POOL, _AFSLOT, IMPLICIT_TABLE, LEGENDARY_SPECIAL, UNIQUE_SPECIAL, UNIQUE_ART, RARITY_MUL, WTYPES, BOWTYPES, _WP_MOD, SLOT_EMOJI, SLOT_NAMES,
// plus the three name tables that live inside mkItem (names, bowNames, _brNames).
const fs = require('fs'); const L = require('./lib.cjs');
const [htmlPath, outPath, commit] = process.argv.slice(2);
const g = L.load(htmlPath), src = g.text;
const ev = head => L.evalLiteral(L.literal(src, head).text);
const pool = ev('const AFFIX_POOL='), afslot = ev('const _AFSLOT='), implicit = ev('const IMPLICIT_TABLE='), legendary = ev('const LEGENDARY_SPECIAL='),
  unique = ev('const UNIQUE_SPECIAL='), uniqueArt = ev('const UNIQUE_ART='), rarityMul = L.evalLiteral(L.literal(src, 'const RARITY_MUL=').text),
  wtypes = ev('const WTYPES='), bowtypes = ev('const BOWTYPES='), wpMod = ev('const _WP_MOD='), slotEmoji = L.evalLiteral(L.literal(src, 'const SLOT_EMOJI=').text),
  slotNames = L.evalLiteral(L.literal(src, 'const SLOT_NAMES=').text);
const mk = src.indexOf('function mkItem(');
const names = L.evalLiteral(L.literal(src, '  const names=', mk).text), bowNames = L.evalLiteral(L.literal(src, '  const bowNames=', mk).text),
  brNames = L.evalLiteral(L.literal(src, '    const _brNames=', mk).text);
const s = v => JSON.stringify(v);
const n = v => v == null ? 'double.NaN' : (Number.isInteger(v) ? v + '.0' : String(v));
const arr = (a, f) => 'new[]{' + a.map(f).join(',') + '}';
const darr = a => 'new double[]{' + a.map(n).join(',') + '}';
let o = '';
const w = t => { o += t + '\n'; };
w('// GENERATED by unity/Tools/drop-oracle/export-tables.cjs from the original game.html (' + commit + ', sha256 ' + g.sha + '). Do not edit by hand.');
w('// Source tables: AFFIX_POOL, _AFSLOT, IMPLICIT_TABLE, LEGENDARY_SPECIAL, UNIQUE_SPECIAL, UNIQUE_ART, RARITY_MUL, WTYPES, BOWTYPES, _WP_MOD, SLOT_EMOJI, SLOT_NAMES, and mkItem names/bowNames/_brNames.');
w('using System.Collections.Generic;');
w('namespace Exoduser.UnityPort.Core {');
w(' public sealed class AffixPoolEntry { public string Id, Unit, Group, BrType; public int Type, MinGrade; public double[] Tiers, TierW; public string[] Slots; public double Weight, SkewRoll; }');
w(' public sealed class ImplicitDef { public string Ko, Stat; public double Lo, Hi; }');
w(' // Roll > 0: integer uniform roll [RollLo,RollHi]; Scale != 0 stores roll*Scale (web: _us.scale).');
w(' public sealed class SpecialDef { public string Key, Ko, Stat; public double Val; public bool HasRoll; public int RollLo, RollHi; public double Scale; }');
w(' public sealed class UniqueArtDef { public string Id, Ko; }');
w(' public sealed class WeaponTypeDef { public string Key, Name, Emoji; public double AtkMul, StCost, SpdMul, ArcW, Range, Stagger, ProjSpd; }');
w(' public static class DropTablesData {');
w('  public const string WebCommit = ' + s(commit) + ', WebSha256 = ' + s(g.sha) + ';');
w('  public static readonly double[] RarityMul = ' + darr(rarityMul) + ';');
w('  public static readonly string[] SlotNames = ' + arr(slotNames, s) + ';');
w('  public static readonly string[] SlotEmoji = ' + arr(slotEmoji, s) + ';');
w('  public static readonly Dictionary<string, string> AfSlot = new Dictionary<string, string> {');
for (const k of Object.keys(afslot)) w('   {' + s(k) + ',' + s(afslot[k]) + '},');
w('  };');
w('  public static readonly AffixPoolEntry[] AffixPool = new[] {');
for (const a of pool) w('   new AffixPoolEntry{Id=' + s(a.id) + ',Type=' + a.type + ',Tiers=' + darr(a.tiers) + ',Unit=' + s(a.unit) + ',Slots=' + arr(a.slots, s) + ',Group=' + s(a.group) + ',Weight=' + n(a.weight) +
  (a.tierW ? ',TierW=' + darr(a.tierW) : '') + (a.skewRoll ? ',SkewRoll=' + n(a.skewRoll) : '') + (a.brType ? ',BrType=' + s(a.brType) : '') + (a.minGrade ? ',MinGrade=' + a.minGrade : '') + '},');
w('  };');
w('  public static readonly Dictionary<string, ImplicitDef> Implicit = new Dictionary<string, ImplicitDef> {');
for (const k of Object.keys(implicit)) { const d = implicit[k]; w('   {' + s(k) + ',new ImplicitDef{Ko=' + s(d.ko) + ',Stat=' + s(d.stat) + ',Lo=' + n(d.val[0]) + ',Hi=' + n(d.val[1]) + '}},'); }
w('  };');
const special = (name, tbl) => {
  w('  public static readonly SpecialDef[] ' + name + ' = new[] {');
  for (const k of Object.keys(tbl)) { const d = tbl[k]; w('   new SpecialDef{Key=' + s(k) + ',Ko=' + s(d.ko) + ',Stat=' + s(d.stat) + ',Val=' + n(d.val) + (d.roll ? ',HasRoll=true,RollLo=' + d.roll[0] + ',RollHi=' + d.roll[1] : '') + (d.scale ? ',Scale=' + n(d.scale) : '') + '},'); }
  w('  };');
};
special('Legendary', legendary); special('Unique', unique);
w('  public static readonly Dictionary<string, UniqueArtDef[]> UniqueArt = new Dictionary<string, UniqueArtDef[]> {');
for (const k of Object.keys(uniqueArt)) w('   {' + s(k) + ',' + arr(uniqueArt[k], d => 'new UniqueArtDef{Id=' + s(d.id) + ',Ko=' + s(d.ko) + '}') + '},');
w('  };');
const wt = (name, tbl, bow) => {
  w('  public static readonly WeaponTypeDef[] ' + name + ' = new[] {');
  for (const k of Object.keys(tbl)) { const d = tbl[k]; w('   new WeaponTypeDef{Key=' + s(k) + ',Name=' + s(d.name) + ',Emoji=' + s(d.emoji) + ',AtkMul=' + n(d.atkMul) + ',StCost=' + n(d.stCost) + ',SpdMul=' + n(d.spdMul) + (bow ? ',Range=' + n(d.range) + ',ProjSpd=' + n(d.projSpd) : ',ArcW=' + n(d.arcW) + ',Range=' + n(d.range) + ',Stagger=' + n(d.stagger)) + '},'); }
  w('  };');
};
wt('WeaponTypes', wtypes, false); wt('BowTypes', bowtypes, true);
w('  // _WP_MOD[el][min(tier,4)]');
w('  public static readonly string[][] WeaponMod = new[] {');
for (const k of Object.keys(wpMod)) w('   ' + arr(wpMod[k], s) + ',');
w('  };');
const nameTable = (name, tbl, keys) => {
  w('  public static readonly Dictionary<string, string[][]> ' + name + ' = new Dictionary<string, string[][]> {');
  for (const k of keys) { const t = tbl[k]; if (!t) continue; w('   {' + s(k) + ',new[]{' + Object.keys(t).map(e => arr(t[e], s)).join(',') + '}},'); }
  w('  };');
};
nameTable('Names', names, Object.keys(names));
nameTable('BowNames', bowNames, Object.keys(bowNames));
nameTable('BraceletNames', brNames, Object.keys(brNames));
w(' }');
w('}');
fs.writeFileSync(outPath, o);
console.log(JSON.stringify({ pool: pool.length, implicit: Object.keys(implicit).length, legendary: Object.keys(legendary).length, unique: Object.keys(unique).length, uniqueArt: Object.keys(uniqueArt).length, names: Object.keys(names), wpMod: Object.keys(wpMod), brNames: Object.keys(brNames), brEls: Object.keys(brNames.demon) }));
