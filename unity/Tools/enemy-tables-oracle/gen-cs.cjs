// Emits EnemyTables.cs / EliteTables.cs from oracle.json (= the original tables evaluated in the Node VM). Nothing is typed by hand.
//   node gen-cs.cjs [--oracle oracle.json] [--out <Runtime/Core/Combat/Enemy>]
const fs=require('node:fs'),path=require('node:path');
const arg=(k,d)=>{const i=process.argv.indexOf(k);return i<0?d:process.argv[i+1];};
const oracle=JSON.parse(fs.readFileSync(arg('--oracle',path.join(__dirname,'oracle.json')),'utf8'));
const outDir=arg('--out',path.join(__dirname,'../../Assets/Exoduser/Runtime/Core/Combat/Enemy'));
const T=oracle.tables,src=oracle.source;
const num=v=>{if(typeof v!=='number'||!isFinite(v))throw Error('not a finite number: '+v);return String(v);};
const str=v=>{if(typeof v!=='string')throw Error('not a string: '+v);return JSON.stringify(v);};
const wrapRows=(parts,wrap)=>{const rows=[];for(let i=0;i<parts.length;i+=wrap)rows.push('            '+parts.slice(i,i+wrap).join(', '));return rows.join(',\n');};
const nums=(a,wrap=12)=>wrapRows(a.map(num),wrap);
const strs=(a,wrap=6)=>wrapRows(a.map(str),wrap);
const sameKeys=(list,keys,what)=>{for(const o of list)if(Object.keys(o).join()!==keys.join())throw Error(what+' key mismatch: '+Object.keys(o));};
const anchor=n=>{const a=src.anchors.find(x=>x.name===n);if(!a)throw Error('no anchor '+n);return 'game.html '+a.start+(a.end>a.start?'-'+a.end:'');};
const header='// GENERATED by unity/Tools/enemy-tables-oracle/gen-cs.cjs from oracle.json — do not edit by hand (CX-01).\n'
 +'// Source: '+src.path+' sha256 '+src.sha256.slice(0,16)+'… ('+src.lines+' lines, repo HEAD '+src.head.slice(0,9)+', game.html '+src.gameHtmlWorkingTreeState+'). The oracle project compares every value with the original.\n';
const lens=Object.entries(oracle.lengths).filter(([k])=>/^_?ETYPE/.test(k)).map(([k,v])=>k+'='+v).join(', ');
const rareKeys=Object.keys(T.RARE_ETYPE);
const rareRows=rareKeys.map(k=>{const r=T.RARE_ETYPE[k];sameKeys([r],['name','hp','atk','spd','r','poise','col'],'RARE_ETYPE');
 return '            new RareEnemyDef { Etype = '+k+', Name = '+str(r.name)+', Hp = '+num(r.hp)+', Atk = '+num(r.atk)+', Spd = '+num(r.spd)+', R = '+num(r.r)+', Poise = '+num(r.poise)+', Col = '+str(r.col)+' }';}).join(',\n');
const stgRows=T.STG.map(s=>{sameKeys([s],['n','kr','w','f','ac','bn','be','monLv','hell','hellFloor','isHellBoss','chapter'],'STG');
 return '            new StageDef { N = '+str(s.n)+', Kr = '+str(s.kr)+', W = '+str(s.w)+', F = '+str(s.f)+', Ac = '+str(s.ac)+', Bn = '+str(s.bn)+', Be = '+num(s.be)+', MonLv = '+num(s.monLv)+', Hell = '+num(s.hell)+', HellFloor = '+num(s.hellFloor)+', IsHellBoss = '+(s.isHellBoss?'true':'false')+', Chapter = '+num(s.chapter)+' }';}).join(',\n');

const enemy=header+`using System;

namespace Exoduser.UnityPort.Core
{
    // One row of RARE_ETYPE (${anchor('RARE_ETYPE')}).
    public sealed class RareEnemyDef
    {
        public int Etype;
        public string Name, Col;
        public double Hp, Atk, Spd, R, Poise;
    }

    // One entry of STG (${anchor('STG loop')}), generated by the original loop over CHAPTER_STAGES / HELL_THEMES / HELL_BOSSES.
    public sealed class StageDef
    {
        public string N, Kr, W, F, Ac, Bn;
        public int Be, MonLv, Hell, HellFloor, Chapter;
        public bool IsHellBoss;
    }

    // Enemy stat tables of the web game (etype 0..89 + rare 90..99), values verbatim. Index = etype.
    // Lengths are kept exactly as the original (no padding): ${lens}.
    public static class EnemyTables
    {
        public const int EtypeCount = ${T.ETYPE_HP.length};
        public const int EresRows = ${T.ETYPE_ERES.length};
        public const int ElementCount = 7; // EL order: P=0 F=1 I=2 D=3 L=4 H=5 E=6

        // ETYPE_HP (${anchor('ETYPE_HP')})
        public static readonly double[] Hp = {
${nums(T.ETYPE_HP)}
        };
        // ETYPE_ATK (${anchor('ETYPE_ATK')})
        public static readonly double[] Atk = {
${nums(T.ETYPE_ATK)}
        };
        // _ETYPE_SPD_RAW (${anchor('_ETYPE_SPD_RAW')})
        public static readonly double[] SpdRaw = {
${nums(T._ETYPE_SPD_RAW)}
        };
        // ETYPE_SPD = _ETYPE_SPD_RAW.map(v=>v===0?0:Math.max(0.2,v*1.3)) (${anchor('ETYPE_SPD')})
        public static readonly double[] Spd = BuildSpd();
        static double[] BuildSpd()
        {
            var t = new double[SpdRaw.Length];
            for (int i = 0; i < t.Length; i++) t[i] = SpdRaw[i] == 0 ? 0 : Math.Max(0.2, SpdRaw[i] * 1.3);
            return t;
        }
        // ETYPE_R (${anchor('ETYPE_R')})
        public static readonly double[] R = {
${nums(T.ETYPE_R)}
        };
        // ETYPE_RANGE (${anchor('ETYPE_RANGE')})
        public static readonly double[] Range = {
${nums(T.ETYPE_RANGE)}
        };
        // ETYPE_POISE (${anchor('ETYPE_POISE')})
        public static readonly double[] Poise = {
${nums(T.ETYPE_POISE)}
        };
        // ETYPE_SHIELD (${anchor('ETYPE_SHIELD')})
        public static readonly double[] Shield = {
${nums(T.ETYPE_SHIELD)}
        };
        // ETYPE_COL (${anchor('ETYPE_COL')}) — colors stay strings as in the web
        public static readonly string[] Col = {
${strs(T.ETYPE_COL)}
        };
        // ETYPE_COLS (${anchor('ETYPE_COLS')})
        public static readonly string[] Cols = {
${strs(T.ETYPE_COLS)}
        };

        // ETYPE_ERES (${anchor('ETYPE_ERES')}): ${T.ETYPE_ERES.length} rows x 7 elements. The web only declares it as all zeros (no mutation site in game.html).
        public static readonly double[][] Eres = BuildEres();
        static double[][] BuildEres()
        {
            var t = new double[EresRows][];
            for (int i = 0; i < t.Length; i++) t[i] = new double[ElementCount];
            return t;
        }

        // RARE_ETYPE (${anchor('RARE_ETYPE')}), keys ${rareKeys[0]}..${rareKeys[rareKeys.length-1]}
        public static readonly RareEnemyDef[] Rare = {
${rareRows}
        };
        // isRareEtype (${anchor('isRareEtype')}): et>=90&&et<=99
        public static bool IsRareEtype(int et) { return et >= 90 && et <= 99; }
        public static RareEnemyDef FindRare(int etype)
        {
            for (int i = 0; i < Rare.Length; i++) if (Rare[i].Etype == etype) return Rare[i];
            return null;
        }

        // DIFF_LV_OFF (${anchor('DIFF_LV_OFF')}), DIFF_MUL (${anchor('DIFF_MUL')})
        public static readonly int[] DiffLvOff = { ${T.DIFF_LV_OFF.map(num).join(', ')} };
        public static readonly double[] DiffMul = { ${T.DIFF_MUL.map(num).join(', ')} };

        // SI_TO_HELL / SI_TO_FLOOR (${anchor('SI_TO_HELL+SI_TO_FLOOR loop')}), TOTAL_STAGES = ${T.TOTAL_STAGES}
        public const int TotalStages = ${T.TOTAL_STAGES};
        public static readonly byte[] SiToHell = { ${T.SI_TO_HELL.map(num).join(', ')} };
        public static readonly byte[] SiToFloor = { ${T.SI_TO_FLOOR.map(num).join(', ')} };

        // STG (${anchor('STG loop')}), ${T.STG.length} stages
        public static readonly StageDef[] Stg = {
${stgRows}
        };
    }
}
`;
fs.mkdirSync(outDir,{recursive:true});
fs.writeFileSync(path.join(outDir,'EnemyTables.cs'),enemy.replace(/\r?\n/g,'\n'));

sameKeys(T.ELITE_TIERS,['name','col','mods','hpMul','atkMul','dropBonus','scaleMul'],'ELITE_TIERS');sameKeys(T.MOD_DEFS,['id','name','col','hell'],'MOD_DEFS');
const elite=header+`
namespace Exoduser.UnityPort.Core
{
    // One entry of ELITE_TIERS (${anchor('ELITE_TIERS')}).
    public sealed class EliteTierDef
    {
        public string Name, Col;
        public int Mods;
        public double HpMul, AtkMul, DropBonus, ScaleMul;
    }

    // One entry of MOD_DEFS (${anchor('MOD_DEFS')}); the web entries carry only these data fields (no functions).
    public sealed class ModDef
    {
        public string Id, Name, Col;
        public int Hell;
    }

    // Elite tier / modifier tables, values verbatim.
    public static class EliteTables
    {
        public static readonly EliteTierDef[] Tiers = {
${T.ELITE_TIERS.map(t=>'            new EliteTierDef { Name = '+str(t.name)+', Col = '+str(t.col)+', Mods = '+num(t.mods)+', HpMul = '+num(t.hpMul)+', AtkMul = '+num(t.atkMul)+', DropBonus = '+num(t.dropBonus)+', ScaleMul = '+num(t.scaleMul)+' }').join(',\n')}
        };
        // ELITE_PROB (${anchor('ELITE_PROB')}): per chapter [magic, rare, champion]
        public static readonly double[][] Prob = {
${T.ELITE_PROB.map(p=>'            new double[] { '+p.map(num).join(', ')+' }').join(',\n')}
        };
        public static readonly ModDef[] Mods = {
${T.MOD_DEFS.map(m=>'            new ModDef { Id = '+str(m.id)+', Name = '+str(m.name)+', Col = '+str(m.col)+', Hell = '+num(m.hell)+' }').join(',\n')}
        };
    }
}
`;
fs.writeFileSync(path.join(outDir,'EliteTables.cs'),elite.replace(/\r?\n/g,'\n'));
console.log('written',outDir);
