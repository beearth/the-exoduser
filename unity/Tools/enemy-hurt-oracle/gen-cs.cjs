// CX-04a generator: emits Runtime/Core/EnemyHurtTables.cs (ELP particle colours, _UNDEAD_ET) from oracle.json (values come from the original text evaluated in Node).
//   node gen-cs.cjs [--oracle oracle.json] [--project <unity project dir>]
// EnemyHurt.cs / EnemyHurtContext.cs / EnemySpawn.Hurt.cs are hand-written ports; the oracle project checks them against the original.
const fs=require('node:fs'),path=require('node:path');
const arg=(k,d)=>{const i=process.argv.indexOf(k);return i<0?d:process.argv[i+1];};
const o=JSON.parse(fs.readFileSync(path.resolve(arg('--oracle',path.join(__dirname,'oracle.json'))),'utf8'));
const project=path.resolve(arg('--project',path.join(__dirname,'../..')));
const s=o.source,a=n=>o.source.anchors.find(x=>x.name===n);
const code='// GENERATED by unity/Tools/enemy-hurt-oracle/gen-cs.cjs from oracle.json — do not edit by hand (CX-04a).\n'+
'// Source: '+s.path+' sha256 '+s.sha256.slice(0,16)+'… ('+s.lines+' lines, repo HEAD '+(s.head||'?').slice(0,9)+'). The oracle project compares both tables with the original.\n'+
'using System;\n\nnamespace Exoduser.UnityPort.Core\n{\n'+
'    // ELP (game.html '+a('ELP').start+'): particle colour per element index; _UNDEAD_ET (game.html '+a('_UNDEAD_ET').start+'): etypes that take the holy-power (antiRevive) bonus.\n'+
'    public static class EnemyHurtTables\n    {\n'+
'        public static readonly string[] ParticleColors = { '+o.tables.ELP.map(x=>JSON.stringify(x)).join(', ')+' };\n'+
'        static readonly int[] Undead = { '+o.tables.UNDEAD_ET.join(', ')+' };\n'+
'        public static bool IsUndead(int etype) { return Array.IndexOf(Undead, etype) >= 0; }\n'+
'        public static int UndeadCount { get { return Undead.Length; } }\n    }\n}\n';
fs.writeFileSync(path.join(project,'Assets/Exoduser/Runtime/Core/EnemyHurtTables.cs'),code);
console.log(JSON.stringify({elp:o.tables.ELP.length,undead:o.tables.UNDEAD_ET.length}));
