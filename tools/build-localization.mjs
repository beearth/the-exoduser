import fs from 'node:fs';
import vm from 'node:vm';
import {languages,loadCatalogs} from './localization-catalog.mjs';

const draft=process.argv.includes('--draft');
const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const stories={},ui={en:{}},lobbyMs=read('localization/lobby-ms.json');
const source=['ui-source','ui-extra-source','ui-growth-source'].flatMap(name=>read('localization/'+name+'.json'));
const terminology=read('localization/terminology.json');
const needed=read('localization/ui-needed.json');
const catalogs=loadCatalogs();
for(const {key,en}of source)ui.en[key]=en;
const aliases=fs.existsSync('localization/ui-aliases.json')?read('localization/ui-aliases.json'):[];
for(const code of languages.filter(c=>c!=='ko')){
 const story='localization/character-story/'+code+'.json';
 if(fs.existsSync(story))stories[code]=read(story);else if(!draft)throw Error('Missing story: '+code);
 if(code!=='en')ui[code]={};
 const base={...catalogs.lobby[code],...catalogs.tables[code]};
 for(const {key,en}of source){
  if(!catalogs.tables[code]?.[key]&&catalogs.lobby[code]?.[key])ui[code][key]=catalogs.lobby[code][key];
  if(/^(LMB|RMB|MMB|Mouse4|Mouse5|★|MAX|DMG|SP|AP|ST|HP|MP|CT|ATK|DEF|eDEF|DPS)$/.test(en))ui[code][key]=en;
 }
 for(const {key,alias,en}of aliases){
  const value=code==='en'?en:base[alias];
  if(value)ui[code][key]=(key.match(/^\s*/)?.[0]||'')+value.trim()+(key.match(/\s*$/)?.[0]||'');
 }
 const file='localization/ui/'+code+'.json';
 const translated=fs.existsSync(file)?read(file):{};
 Object.assign(ui[code],translated);
 const extra='localization/ui-extra/'+code+'.json';
 if(fs.existsSync(extra))Object.assign(ui[code],read(extra));
 const growth='localization/ui-growth/'+code+'.json';
 if(fs.existsSync(growth))Object.assign(ui[code],read(growth));
 Object.assign(ui[code],terminology[code]||{});
 if(!draft){
  const incomplete=(needed[code]||[]).filter(({key})=>typeof translated[key]!=='string'||!translated[key].trim());
  if(incomplete.length)throw Error(`${code}: ${incomplete.length} audited English fallback gaps still need explicit translations`);
  const missing=source.filter(row=>!ui[code][row.key]&&!base[row.key]);
  if(missing.length)throw Error(`${code}: ${missing.length} untranslated keys`);
 }
}
const bundle={version:'20260909',stories,ui,lobbyMs};
fs.writeFileSync('localization-data.js','// Generated by tools/build-localization.mjs. Edit localization/ sources.\n'+'globalThis.ExoduserLocalizationData='+JSON.stringify(bundle)+';\n');
console.log({stories:Object.keys(stories).length,uiSource:source.length,draft});
