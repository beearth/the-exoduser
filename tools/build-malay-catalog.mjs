// Malay shares much vocabulary with Indonesian; explicit adaptation + reviewed overrides.
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync('lang_id.js','utf8'),ctx);
const glossary=JSON.parse(fs.readFileSync('localization/ms-adaptation.json','utf8'));
const escape=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const pattern=new RegExp('\\b('+Object.keys(glossary).sort((a,b)=>b.length-a.length).map(escape).join('|')+')\\b','gi');
const translate=text=>text.replace(pattern,match=>{
 const result=glossary[match.toLowerCase()];
 if(match===match.toUpperCase())return result.toUpperCase();
 return /^[A-Z]/.test(match)?result[0].toUpperCase()+result.slice(1):result;
});
const overrides=fs.existsSync('localization/ms-overrides.json')?JSON.parse(fs.readFileSync('localization/ms-overrides.json','utf8')):{};
const tables={};
for(const suffix of ['','_PFX','_BASE']){
 const base=vm.runInContext('_ID'+suffix,ctx);
 tables[suffix]=Object.fromEntries(Object.entries(base).map(([k,v])=>[k,translate(v)]));
 Object.assign(tables[suffix],overrides[suffix]||{});
}
// Explicit corrections also win for direct UI lookups before compound-name lookup.
Object.assign(tables[''],overrides._PFX||{},overrides._BASE||{},overrides['']||{});
const output='// Bahasa Melayu — generated by tools/build-malay-catalog.mjs.\n'+Object.entries(tables).map(([suffix,table])=>'const _MS'+suffix+'='+JSON.stringify(table,null,2)+';\n').join('');
fs.writeFileSync('lang_ms.js',output);
console.log(Object.fromEntries(Object.entries(tables).map(([key,values])=>[key||'MAIN',Object.keys(values).length])));
