// Capture reviewed pure CH1-1 geometry only. Never run the game's page or globals.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { decodeTileRLE, encodeTileRLE } from '../engine/fdg/legacy.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha = value => createHash('sha256').update(value).digest('hex');
const REVIEWED = Object.freeze({
  _buildCh1StartForestRLE: '8f6ad81bd9183d5e58deb99ccddac189d7a59a00cdab6b6157069f17a87d6ca8',
  _applyCh1StartNorthGate: '9bae0a90422beeef9ecaae99893ae82b589bd12a42e5cf9696667e87f91e0a18',
});

function balanced(source, opening) {
  let depth = 0, quote = '', line = false, block = false;
  for (let i = opening; i < source.length; i++) {
    const c = source[i], next = source[i + 1];
    if (line) { if (c === '\n') line = false; continue; }
    if (block) { if (c === '*' && next === '/') { block = false; i++; } continue; }
    if (quote) { if (c === '\\') i++; else if (c === quote) quote = ''; continue; }
    if (c === '/' && next === '/') { line = true; i++; continue; }
    if (c === '/' && next === '*') { block = true; i++; continue; }
    if (c === '"' || c === "'" || c === '`') { quote = c; continue; }
    if (c === '{') depth++;
    if (c === '}' && --depth === 0) return i + 1;
  }
  throw new Error('닫는 중괄호가 없습니다.');
}

function reviewedFunction(source, name) {
  const marker = `function ${name}(`;
  const start = source.indexOf(marker);
  if (start < 0 || source.indexOf(marker, start + marker.length) !== -1) throw new Error(`${name}: 정확히 하나의 함수가 필요합니다.`);
  const opening = source.indexOf('{', start);
  const code = source.slice(start, balanced(source, opening));
  if (sha(code) !== REVIEWED[name]) throw new Error(`${name}가 변경됐습니다. 맵 SSOT와 순수 함수를 다시 검토한 후 승인된 SHA를 갱신하세요.`);
  return code;
}

export async function captureSourceMap() {
  const gameSource = await fs.readFile(path.join(ROOT, 'game.html'), 'utf8');
  const templateSource = await fs.readFile(path.join(ROOT, 'maps_data.js'), 'utf8');
  const marker = templateSource.indexOf('FIXED_MAPS[0]=');
  if (marker < 0) throw new Error('FIXED_MAPS[0]가 없습니다.');
  const opening = templateSource.indexOf('{', marker);
  const template = JSON.parse(templateSource.slice(opening, balanced(templateSource, opening)));
  if (template.mw !== 200 || template.mh !== 200) throw new Error('CH1-1 200×200 계약이 변경됐습니다.');
  const funcs = Object.keys(REVIEWED).map(name => reviewedFunction(gameSource, name));
  // Exact reviewed source hashes precede execution. Context has no Node, browser,
  // network, filesystem, timers or dynamic code generation capability.
  const context = vm.createContext({ _rleEncodeGrid: values => encodeTileRLE(values) }, { codeGeneration: { strings: false, wasm: false } });
  const result = new vm.Script(`${funcs.join('\n')}\n(() => {
    const rle = _buildCh1StartForestRLE(200, 200);
    const raw = []; for (let i=0;i<rle.length;i+=2) for(let j=0;j<rle[i+1];j++) raw.push(rle[i]);
    const map = []; for(let y=0;y<200;y++) map.push(raw.slice(y*200,(y+1)*200).map(v=>v===1?0:1));
    const gate = _applyCh1StartNorthGate(map,200,200);
    return {tiles:map.flat().map(v=>v===1?0:1),exit:gate.exits[1]};
  })()`, { filename: 'fdg-reviewed-ch1-geometry.js' }).runInContext(context, { timeout: 1000 });
  const tileRLE = encodeTileRLE(result.tiles);
  decodeTileRLE(tileRLE); // require complete coverage before saving.
  const room = template.rooms.find(entry => entry.type === 'start');
  if (!room) throw new Error('CH1-1 start 방이 없습니다.');
  template.tileRLE = tileRLE;
  return {
    schemaVersion: 1, stage: 0, width: 200, height: 200, tileSize: 40,
    start: { x: Math.floor(room.cx), y: Math.floor(room.cy) }, exit: { x: result.exit.x, y: result.exit.y },
    tileRLE, template,
    provenance: {
      source: 'game.html + maps_data.js', gameSHA256: sha(gameSource), mapsDataSHA256: sha(templateSource),
      functions: REVIEWED, geometry: '_buildCh1StartForestRLE + _applyCh1StartNorthGate',
      stage: 'CH1-1 canonical tile geometry snapshot', tileLegend: '1=floor; 0/2/3=blocked',
      excludes: ['production object collision', 'CH1 high-ground band', 'baked environment', 'enemy and gate gameplay'],
      application: 'FDG preview only; live _MAP_COMPOSE integration is not installed',
    },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const data = await captureSourceMap();
  const target = path.join(ROOT, 'engine/fdg/source-map.js');
  const output = `// Generated by tools/fdg-catalog.mjs from exact reviewed pure geometry.\nexport const SOURCE_MAP = ${JSON.stringify(data, null, 2)};\n`;
  if (process.argv.includes('--check')) {
    if (await fs.readFile(target, 'utf8') !== output) throw new Error('FDG canonical geometry snapshot가 원본과 다릅니다.');
    console.log('FDG canonical geometry snapshot: current');
  } else {
    await fs.writeFile(target, output);
    console.log(`Captured CH1-1: ${data.width}×${data.height}, START(${data.start.x},${data.start.y}) EXIT(${data.exit.x},${data.exit.y})`);
  }
}
