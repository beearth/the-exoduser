"""Measure each 256px enemy atlas cell's alpha>20 silhouette (no image writes)."""
import argparse
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "unity/Assets/Exoduser/Resources/Art/enemy"
OUTPUT = ROOT / "unity/Assets/Exoduser/Resources/Data/enemy_body_extents.json"
CELL = 256
THRESHOLD = 20
DIRECTIONS = ("east", "north", "north_east", "north_west", "south", "south_east", "south_west", "west")


def measure():
    bodies = []
    for walking in (False, True):
        for direction in DIRECTIONS:
            name = "atlas_ch1_8dir_" + ("walk_" if walking else "") + direction
            with Image.open(ART / (name + ".png")) as source:
                width, height = source.size
                if width % CELL or height % CELL:
                    raise ValueError(f"{name}: non-256 cell dimensions {source.size}")
                alpha = source.convert("RGBA").getchannel("A").point(lambda a: 255 if a > THRESHOLD else 0)
                for y in range(0, height, CELL):
                    for x in range(0, width, CELL):
                        box = alpha.crop((x, y, x + CELL, y + CELL)).getbbox()
                        if box is None:
                            continue  # No visible body: runtime must retain legacy placement.
                        bodies.append({"texture": name, "x": x, "y": height - y - CELL,
                                       "cell": (y // CELL) * 8 + (x // CELL // (4 if walking else 1)),
                                       "frame": x // CELL % 4 if walking else 0,
                                       "bottom": (CELL - box[3]) / CELL, "top": (CELL - box[1]) / CELL})
    return {"version": 1, "cellSize": CELL, "alphaThreshold": THRESHOLD, "bodies": bodies}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-only", action="store_true", help="Compare generated bytes; never write the table")
    args = parser.parse_args()
    data = measure()
    encoded = (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    if args.check_only:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != encoded:
            raise SystemExit("FAIL enemy-body-extents: missing/stale silhouette table; regenerate with this script")
    else:
        OUTPUT.write_bytes(encoded)
    heights = [(b["top"] - b["bottom"]) * CELL for b in data["bodies"]]
    print(f"enemy-body-extents: {'CHECK' if args.check_only else 'GENERATED'} PASS; "
          f"16 atlases, {len(heights)} visible cells, height {min(heights):g}..{max(heights):g}px, alpha>{THRESHOLD}")


if __name__ == "__main__":
    main()
